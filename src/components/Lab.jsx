import { useEffect, useMemo, useRef, useState } from 'react';
import { gsap, useGSAP } from '../lib/gsap';
import { bus, toast } from '../lib/bus';
import CodeHeading from './CodeHeading';
// the real file that generates the galaxy — imported as text, so it can't drift
import source from '../lib/generateGalaxy.js?raw';

const FILE = 'src/lib/generateGalaxy.js';

// tiny JS highlighter — just enough for this one file
const TOKEN =
  /(\/\/[^\n]*)|('(?:[^'\\\n]|\\.)*')|\b(export|function|const|let|for|return|if|else|new|of)\b|\b(Math|Float32Array|Array)\b|\b(\d+(?:\.\d+)?)\b|([A-Za-z_$][\w$]*)(?=\s*\()/g;
const CLASSES = ['tk-com', 'tk-str', 'tk-key', 'tk-bi', 'tk-num', 'tk-fn'];

function highlight(code) {
  const out = [];
  let last = 0;
  let m;
  let k = 0;
  TOKEN.lastIndex = 0;
  while ((m = TOKEN.exec(code))) {
    if (m.index > last) out.push(code.slice(last, m.index));
    const group = m.slice(1).findIndex(Boolean);
    out.push(
      <span key={k++} className={CLASSES[group]}>
        {m[0]}
      </span>
    );
    last = TOKEN.lastIndex;
  }
  out.push(code.slice(last));
  return out;
}

const round = (n, d = 2) => Math.round(n * 10 ** d) / 10 ** d;

export default function Lab() {
  const ref = useRef(null);
  const [params, setParams] = useState({ count: 70000, branches: 4, spin: 1.1, randomness: 0.32 });
  const [copied, setCopied] = useState(false);
  const lines = useMemo(() => source.trimEnd().split('\n'), []);
  const code = useMemo(() => highlight(source.trimEnd()), []);

  // sync with whatever the galaxy is actually running (phones use fewer particles)
  useEffect(() => {
    bus.emit('galaxy:params', p => setParams(p));
  }, []);

  useGSAP(
    () => {
      gsap.from('.lab__panel', {
        y: 60,
        opacity: 0,
        duration: 1.2,
        ease: 'expo.out',
        stagger: 0.15,
        scrollTrigger: { trigger: '.lab__grid', start: 'top 85%', once: true }
      });
    },
    { scope: ref }
  );

  const set = (key, value) => setParams(p => ({ ...p, [key]: value }));

  const run = next => {
    const p = next ?? params;
    bus.emit('galaxy:rebuild', { branches: p.branches, spin: p.spin, randomness: p.randomness });
    toast(`› generateGalaxy() → ${p.count.toLocaleString()} particles`);
  };

  const randomize = () => {
    const next = {
      ...params,
      branches: 2 + Math.floor(Math.random() * 6),
      spin: round(Math.random() * 4 - 2, 1),
      randomness: round(0.1 + Math.random() * 0.6)
    };
    setParams(next);
    run(next);
  };

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(source);
      setCopied(true);
      setTimeout(() => setCopied(false), 1600);
    } catch {
      toast('// clipboard blocked by the browser');
    }
  };

  const call = `generateGalaxy({ count: ${params.count}, branches: ${params.branches}, spin: ${params.spin}, randomness: ${params.randomness} })`;

  return (
    <section className="lab section" id="lab" ref={ref}>
      <CodeHeading index="05" note="the galaxy behind this page is generated by the code below. change it.">
        lab
      </CodeHeading>

      <div className="lab__grid">
        <div className="lab__panel lab__controls">
          <div className="panel__bar mono">
            <span>playground</span>
            <span className="c-dim">live</span>
          </div>

          <div className="ctrl">
            <label className="ctrl__label mono">
              branches <b>{params.branches}</b>
            </label>
            <div className="ctrl__pills">
              {[2, 3, 4, 5, 6, 7].map(n => (
                <button
                  key={n}
                  className={`pill mono ${params.branches === n ? 'is-on' : ''}`}
                  onClick={() => set('branches', n)}
                >
                  {n}
                </button>
              ))}
            </div>
          </div>

          <div className="ctrl">
            <label className="ctrl__label mono" htmlFor="spin">
              spin <b>{params.spin}</b>
            </label>
            <input
              id="spin"
              type="range"
              min="-3"
              max="3"
              step="0.1"
              value={params.spin}
              onChange={e => set('spin', parseFloat(e.target.value))}
            />
          </div>

          <div className="ctrl">
            <label className="ctrl__label mono" htmlFor="rand">
              randomness <b>{params.randomness}</b>
            </label>
            <input
              id="rand"
              type="range"
              min="0.05"
              max="1"
              step="0.01"
              value={params.randomness}
              onChange={e => set('randomness', parseFloat(e.target.value))}
            />
          </div>

          <pre className="lab__call mono">
            <code>
              <span className="c-dim">&gt; </span>
              {highlight(call)}
            </code>
          </pre>

          <div className="ctrl__actions">
            <button className="btn btn--primary mono" onClick={() => run()}>
              ▶ run()
            </button>
            <button className="btn mono" onClick={randomize}>
              ⟳ random()
            </button>
          </div>
        </div>

        <div className="lab__panel lab__code">
          <div className="panel__bar mono">
            <span>{FILE}</span>
            <button className="panel__copy mono" onClick={copy}>
              {copied ? 'copied ✓' : 'copy'}
            </button>
          </div>
          <div className="code" data-lenis-prevent>
            <pre className="code__gutter mono" aria-hidden="true">
              {lines.map((_, i) => i + 1).join('\n')}
            </pre>
            <pre className="code__body mono">
              <code>{code}</code>
            </pre>
          </div>
        </div>
      </div>
    </section>
  );
}
